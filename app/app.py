# PlantCare AI - Plant Disease Detection
# End-to-End AI Capstone Project
#
# This is a full-stack machine learning application that detects
# plant diseases from leaf images using a trained CNN model.
#
# Architecture:
#   - Backend:  FastAPI REST API (app/main.py)
#   - Frontend: Streamlit dashboard (streamlit_app.py)
#   - Model:    MobileNetV2 transfer learning (Keras)
#   - Deploy:   Docker containerized, cloud-hosted
#
# To run locally, see README.md for instructions.